"""Generate TypeScript DTOs from FastAPI without querying the database."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "api"))
from app.main import app


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1].replace("-", "_") + "DTO"
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(ts(v) for v in schema.get("anyOf", schema.get("oneOf")))
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties", {})
            return (
                "Record<string, "
                + (ts(extra) if isinstance(extra, dict) else "unknown")
                + ">"
            )
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                "  "
                + json.dumps(k)
                + ("" if k in required else "?")
                + ": "
                + ts(v)
                + ";"
                for k, v in schema["properties"].items()
            )
            + "\n}"
        )
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    schemas = app.openapi()["components"]["schemas"]
    content = "// Generated by docs/api/generar_tipos_consola.py. Do not edit.\n"
    for name, schema in sorted(schemas.items()):
        content += f"export type {name.replace('-', '_')}DTO = {ts(schema)};\n\n"
    return content


if __name__ == "__main__":
    (ROOT / "consola/src/types/rest.ts").write_text(generate(), encoding="utf-8")
